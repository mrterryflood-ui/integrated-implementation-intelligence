import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import {dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const sourcePath='docs/dis/GPT-SESSION-AND-AGENT-OPERATING-CONTRACT.md';
const source=readFileSync(new URL('../../../'+sourcePath,import.meta.url),'utf8');
const version=/^Version:\s*([^|\n]+)/m.exec(source)?.[1].trim();
if(!version)throw new Error('The shared operating contract needs a version.');
const sha256=createHash('sha256').update(source).digest('hex');
const target=fileURLToPath(new URL('../lib/generated/dis-operating-contract.ts',import.meta.url));
const output='// Generated by scripts/sync-operating-contract.mjs. Do not edit by hand.\n'+
 'export const DIS_OPERATING_CONTRACT = '+JSON.stringify({sourcePath,version,sha256,text:source},null,2)+' as const;\n';
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==output)throw new Error('The runtime contract differs from the canonical document. Run node scripts/sync-operating-contract.mjs, review the delta, and rerun behavior tests.');
 console.log('PASS shared operating contract: '+version+' / '+sha256);
}else{
 mkdirSync(dirname(target),{recursive:true});writeFileSync(target,output);
 console.log('Updated runtime operating contract: '+version+' / '+sha256);
}
