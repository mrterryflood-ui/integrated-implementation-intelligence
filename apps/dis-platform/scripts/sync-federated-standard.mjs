import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

// Each protocol is canonical in docs/. Runtime copies must agree byte-for-byte.
const specs=[
  {path:'docs/dis/FEDERATED-EVIDENCE-AND-DECISION-STANDARD.md',
   name:'dis-federated-standard.ts',symbol:'DIS_FEDERATED_STANDARD',
   version:/^Version\s+([^|\n]+)/m},
  {path:'docs/dis/STACK-AGNOSTIC-ENGINEERING-INQUIRY-PROTOCOL.md',
   name:'dis-engineering-standard.ts',symbol:'DIS_ENGINEERING_STANDARD',
   version:/^\*\*Version:\*\*\s*([^|\n]+)/m}
];
for(const spec of specs){
  const source=readFileSync(new URL('../../../'+spec.path,import.meta.url),'utf8');
  const version=spec.version.exec(source)?.[1].trim();
  if(!version)throw new Error('Published standard has no declared version: '+spec.path);
  const output='// Generated by scripts/sync-federated-standard.mjs. Do not edit by hand.\n'+
    'export const '+spec.symbol+' = '+JSON.stringify({sourcePath:spec.path,version,text:source},null,2)+' as const;\n';
  const target=fileURLToPath(new URL('../lib/generated/'+spec.name,import.meta.url));
  const digest=createHash('sha256').update(source).digest('hex');
  if(process.argv.includes('--check')){
    if(readFileSync(target,'utf8')!==output)
      throw new Error('Runtime standard differs from canonical document: '+spec.path);
    console.log('PASS standard '+spec.path+': '+version+' / '+digest);
  }else{
    writeFileSync(target,output);
    console.log('Updated runtime standard '+spec.path+': '+version+' / '+digest);
  }
}
