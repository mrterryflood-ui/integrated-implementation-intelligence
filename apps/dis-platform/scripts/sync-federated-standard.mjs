import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const sourcePath='docs/dis/FEDERATED-EVIDENCE-AND-DECISION-STANDARD.md';
const source=readFileSync(new URL('../../../'+sourcePath,import.meta.url),'utf8');
const version=/^Version\s+([^|\n]+)/m.exec(source)?.[1].trim();
if(!version)throw new Error('The federated standard has no declared version.');
const output='// Generated by scripts/sync-federated-standard.mjs. Do not edit by hand.\n'+
  'export const DIS_FEDERATED_STANDARD = '+JSON.stringify({sourcePath,version,text:source},null,2)+' as const;\n';
const target=fileURLToPath(new URL('../lib/generated/dis-federated-standard.ts',import.meta.url));
const digest=createHash('sha256').update(source).digest('hex');
if(process.argv.includes('--check')){
  if(readFileSync(target,'utf8')!==output)throw new Error('The federated standard runtime copy differs from its canonical document. Run node scripts/sync-federated-standard.mjs and review the diff.');
  console.log('PASS federated standard: '+version+' / '+digest);
}else{
  writeFileSync(target,output);
  console.log('Updated federated standard: '+version+' / '+digest);
}
